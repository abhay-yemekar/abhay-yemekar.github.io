"""
Generates src/data/wordmark.ts: the name as vector outlines in Instrument Sans
at weight 700, width 75%, kerned, for the hero wordmark.

Outlines rather than SVG <text>, for two reasons:
- Chrome counts SVG text as a Largest Contentful Paint candidate, and a
  full-width wordmark would take LCP from the <h1>. Paths aren't candidates.
- The particle field samples the same paths through Path2D, so the particles
  land exactly on the static wordmark in every browser, and canvas font
  support (Firefox has no fontStretch) doesn't matter.

Run with the fontTools that's on the machine (no project dependency):

    python scripts/gen-wordmark.py

fontTools needs a Brotli decoder to read WOFF2. If no Python brotli module is
installed, this borrows Node's built-in one.
"""

import subprocess
import sys
import types
from pathlib import Path

try:
    import brotli  # noqa: F401
except ImportError:

    def _decompress(data: bytes) -> bytes:
        script = "process.stdout.write(require('zlib').brotliDecompressSync(require('fs').readFileSync(0)))"
        return subprocess.run(["node", "-e", script], input=data, capture_output=True, check=True).stdout

    sys.modules["brotli"] = types.SimpleNamespace(decompress=_decompress)

from fontTools.pens.boundsPen import BoundsPen  # noqa: E402
from fontTools.pens.svgPathPen import SVGPathPen  # noqa: E402
from fontTools.pens.transformPen import TransformPen  # noqa: E402
from fontTools.ttLib import TTFont  # noqa: E402
from fontTools.varLib import instancer  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "node_modules/@fontsource-variable/instrument-sans/files/instrument-sans-latin-wdth-normal.woff2"
OUT = ROOT / "src/data/wordmark.ts"
NAME = "ABHAY YEMEKAR"
AXES = {"wght": 700, "wdth": 75}
EM = 1000  # output units per em


def kerning(font: TTFont):
    """Pair adjustments from the GPOS 'kern' feature (PairPos formats 1 and 2)."""
    gpos = font["GPOS"].table
    indices = sorted(
        {i for rec in gpos.FeatureList.FeatureRecord if rec.FeatureTag == "kern" for i in rec.Feature.LookupListIndex}
    )
    subtables = []
    for index in indices:
        lookup = gpos.LookupList.Lookup[index]
        for sub in lookup.SubTable:
            if lookup.LookupType == 9:
                sub = sub.ExtSubTable
            if getattr(sub, "LookupType", 2) == 2:
                subtables.append(sub)

    def pair(left: str, right: str) -> int:
        for sub in subtables:
            if left not in sub.Coverage.glyphs:
                continue
            if sub.Format == 1:
                pairs = sub.PairSet[sub.Coverage.glyphs.index(left)].PairValueRecord
                for record in pairs:
                    if record.SecondGlyph == right:
                        return getattr(record.Value1, "XAdvance", 0) or 0
            elif sub.Format == 2:
                c1 = sub.ClassDef1.classDefs.get(left, 0)
                c2 = sub.ClassDef2.classDefs.get(right, 0)
                value = sub.Class1Record[c1].Class2Record[c2].Value1
                adjust = getattr(value, "XAdvance", 0) or 0
                if adjust:
                    return adjust
        return 0

    return pair


def main() -> None:
    font = instancer.instantiateVariableFont(TTFont(FONT), AXES)
    upem = font["head"].unitsPerEm
    scale = EM / upem
    cmap = font.getBestCmap()
    glyphs = font.getGlyphSet()
    hmtx = font["hmtx"]
    kern = kerning(font)

    bounds = BoundsPen(glyphs)
    glyphs["H"].draw(bounds)
    cap = bounds.bounds[3] * scale

    def outline(text: str):
        names = [cmap[ord(ch)] for ch in text]
        x = 0.0
        out = []
        for i, name in enumerate(names):
            if text[i] != " ":
                pen = SVGPathPen(glyphs, ntos=lambda v: f"{v:.1f}".rstrip("0").rstrip("."))
                # Font units are y-up; SVG is y-down with the baseline at y=0.
                glyphs[name].draw(TransformPen(pen, (scale, 0, 0, -scale, 0, 0)))
                out.append({"x": round(x, 1), "d": pen.getCommands()})
            x += hmtx[name][0] * scale
            if i + 1 < len(names):
                x += kern(name, names[i + 1]) * scale
        return {"width": round(x, 1), "glyphs": out}

    first, last = NAME.split(" ")
    lines = {"wide": outline(NAME), "first": outline(first), "last": outline(last)}

    def ts_line(key: str) -> str:
        line = lines[key]
        rows = ",\n".join(f"      {{ x: {g['x']}, d: '{g['d']}' }}" for g in line["glyphs"])
        return f"  {key}: {{\n    width: {line['width']},\n    glyphs: [\n{rows},\n    ],\n  }},"

    body = "\n".join(ts_line(k) for k in ("wide", "first", "last"))
    OUT.write_text(
        "/**\n"
        " * Generated by scripts/gen-wordmark.py. Don't edit by hand.\n"
        " *\n"
        f" * \"{NAME}\" as kerned outlines of Instrument Sans (wght {AXES['wght']}, wdth {AXES['wdth']}),\n"
        f" * in units of {EM} per em, baseline at y=0, so caps run from -capHeight to 0.\n"
        " */\n"
        "export type WordmarkLine = { width: number; glyphs: { x: number; d: string }[] }\n\n"
        f"export const capHeight = {cap:.1f}\n\n"
        "export const wordmark: Record<'wide' | 'first' | 'last', WordmarkLine> = {\n"
        f"{body}\n"
        "}\n",
        encoding="utf-8",
    )
    widths = ", ".join(f"{k} {v['width'] / EM:.3f}em" for k, v in lines.items())
    print(f"wrote {OUT.relative_to(ROOT)}: cap {cap / EM:.3f}em; {widths}")


if __name__ == "__main__":
    main()
